# =============================================================================
# REQUEST / RESPONSE MODELS
# =============================================================================


class ChatRequest(BaseModel):
    """Incoming chat request."""
    message: str
    conversation_id: Optional[str] = None


class TableData(BaseModel):
    """Structured table result."""
    headers: list
    rows: list


class ChatResponse(BaseModel):
    """Standard chat response format."""
    status: str  # success, error, greeting, off_topic, clarification
    message: str
    is_table: bool = False
    table_data: Optional[TableData] = None
    row_count: int = 0
    preview_row_count: int = 0
    returned_row_count: int = 0
    total_row_count: Optional[int] = None
    export_row_count: Optional[int] = None
    display_row_limit: int = 100
    download_key: Optional[str] = None
    export_id: Optional[str] = None
    export_status: Optional[str] = None
    export_mode: Optional[str] = None
    execution_time_ms: int = 0
    conversation_id: Optional[str] = None
    clarification: Optional[str] = None
    # --- Genie extension fields (populated only when USE_GENIE_BACKEND=true) ---
    # Frontend ignores unknown fields; Phase G7 will add UI components for these.
    suggested_questions: Optional[list] = None
    has_visualization: bool = False
    visualization: Optional[dict] = None
    source: Optional[str] = None
    genie_conversation_id: Optional[str] = None   # audit / multi-turn correlation
    fallback_recommended: Optional[bool] = None   # True when Genie deferred to next pipeline
    genie_message_id: Optional[str] = None        # Genie message ID; used for per-turn traceability
    generated_sql: Optional[str] = None           # SQL generated by Genie; displayed in SqlAccordion (G7)
    query_description: Optional[str] = None        # Genie query.description — context line shown in UI (Q2)
    genie_thought_description: Optional[str] = None  # THOUGHT_TYPE_DESCRIPTION from Genie thoughts (Q2)
    computed_chart_data: Optional[dict] = None      # {data, x_key, y_key} from table summarizer (Q3)
    computed_metrics: Optional[dict] = None         # aggregate stats from table summarizer (Q3)


# =============================================================================
# SERVICE INSTANCES (initialized once per worker)
# =============================================================================

_llm: Optional[LLMService] = None
_sql: Optional[SQLService] = None
_validator: Optional[SQLValidator] = None
_conversations: Optional[ConversationManager] = None
_audit: Optional[AuditService] = None


def _get_services():
    """Lazy-init all services."""
    global _llm, _sql, _validator, _conversations, _audit
    if _llm is None:
        _llm = LLMService()
        _sql = SQLService()
        _validator = SQLValidator()
        _conversations = ConversationManager()
        _audit = AuditService()
    return _llm, _sql, _validator, _conversations, _audit


