def _fast_classify(message: str) -> Optional[str]:
    """Fast pattern-match for PURE greetings only. Skips LLM call.

    Returns a greeting category ONLY if the message is purely a greeting
    (short, no query-indicating keywords). Returns None for anything that
    contains a real data question — even if it starts with "hi".

    Examples:
        "hi" → "hello"
        "how are you?" → "casual"
        "hi can you give me shipments from Mexico?" → None (has query content)
        "hey show me delays" → None (has query content)
    """
    lower = message.lower().strip().rstrip("!?.")

    # Never fast-classify long messages
    if len(lower) > 60:
        return None

    # CRITICAL: If message contains any query-indicating keywords, it's NOT
    # a pure greeting — let it go through the full pipeline
    if has_query_intent(message):
        return None

    # Only match very short messages (≤6 words) with no query content
    word_count = len(lower.split())
    if word_count > 6:
        return None

    # Now safe to check greeting patterns
    for category, patterns in _GREETING_PATTERNS.items():
        if any(lower.startswith(p) or lower == p for p in patterns):
            return category
    return None


def _strip_greeting_prefix(message: str) -> str:
    """Strip greeting prefix from messages that contain a real query.

    'hi can you give me shipments from Mexico?' → 'can you give me shipments from Mexico?'
    'hello, show me delays for ADC' → 'show me delays for ADC'
    'hey' → 'hey' (pure greeting, no stripping)

    Only strips if the remainder contains query content (safety check).
    """
    lower = message.lower().strip()
    for prefix in _GREETING_PREFIXES:
        if lower.startswith(prefix):
            remainder = message[len(prefix):].lstrip(", ")
            # Only strip if the remainder is substantial (has query content)
            if len(remainder) > 3 and has_query_intent(remainder):
                return remainder
    # Also handle "hi, can you..." with comma
    comma_match = re.match(r"^(?:hi|hey|hello|yo)\s*[,!]\s*", message, re.IGNORECASE)
    if comma_match:
        remainder = message[comma_match.end():]
        if len(remainder) > 3 and has_query_intent(remainder):
            return remainder
    return message


def _async_full_export(sql: str, sql_svc, audit, download_key: str):
    """Run full SQL query in background thread for CSV export."""
    try:
        result = sql_svc.execute_query(sql, row_limit=100_000)
        if not result.error and result.rows:
            audit.update_export(download_key=download_key, headers=result.headers, rows=result.rows)
            logger.info(f"Async export done: {download_key} ({len(result.rows)} rows)")
    except Exception as e:
        logger.error(f"Async export error: {e}")


def _preprocess_message(message: str) -> str:
    """Apply business rules preprocessing to user message."""
    processed = message
    processed = convert_country_to_iso(processed)
    return processed


def _elapsed_ms(start_time: float) -> int:
    """Calculate elapsed milliseconds since start_time."""
    return int((time.time() - start_time) * 1000)


def _serialize_value(value) -> str:
    """Convert a value to JSON-serializable string."""
    if value is None:
        return None
    if isinstance(value, (int, float, bool)):
        return value
    return str(value)


def _genie_table_to_table_data(td: Optional[dict]) -> Optional[TableData]:
    """Convert a Genie mapper table_data dict to the TableData Pydantic model.

    The Genie response mapper returns table_data as a plain dict
    {"headers": [...], "rows": [[...], ...]}.  This function wraps it
    into the TableData model that ChatResponse expects.

    Returns None for None, empty dicts, or any falsy value so that
    is_table=False responses never produce a spurious empty TableData.
    """
    if not td:
        return None
    return TableData(
        headers=td.get("headers", []),
        rows=td.get("rows", []),
    )
